/** Small, fast, seedable PRNG (mulberry32). Same seed → same sequence everywhere. */
export type Rng = () => number;

export function mulberry32(seed: number): Rng {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export const range = (rng: Rng, lo: number, hi: number) => lo + (hi - lo) * rng();
export const int = (rng: Rng, lo: number, hiInclusive: number) =>
  Math.floor(range(rng, lo, hiInclusive + 1));
