/**
 * Regenerates tests/fixtures/project.mock.json and its assets in
 * public/fixtures/ from the real pipeline (60 mm cube), so WS-C/D/F build
 * against data that matches what the Studio will publish.
 *
 * Usage: pnpm mock
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { faceNormalsAndAreas } from '../src/lib/geometry/mesh';
import { restingRotation } from '../src/lib/geometry/orient';
import { loadModel, prepareModel } from '../src/lib/geometry/pipeline';
import { generateMat } from '../src/lib/mat/generate';
import type { Annotation, Project, Vec3 } from '../src/lib/types';
import { cube, toBinaryStl } from '../tests/fixtures/shapes';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pub = join(root, 'public/fixtures');
mkdirSync(pub, { recursive: true });

const id = 'mockcube01';
const title = 'Mock cube';
const loaded = await loadModel(toBinaryStl(cube()), 1);
const asPrinted = loaded.candidates.find((c) => c.asPrinted)!;
const prepared = await prepareModel(loaded.meshMm, restingRotation(asPrinted.normal));
const mat = generateMat({
  projectId: id,
  geometryVersion: 1,
  title,
  siteUrl: 'https://exhibitar.vercel.app',
  contactOutlineMm: prepared.footprint.contactOutlineMm,
  shadowOutlineMm: prepared.footprint.shadowOutlineMm,
  contactWeak: prepared.footprint.contactWeak,
});

// Region: the triangles of the cube face that points to FRONT (model −Y → mat +Z).
const { normals } = faceNormalsAndAreas(prepared.frozenMesh);
const front: number[] = [];
for (let t = 0; t < normals.length / 3; t++) if (normals[t * 3 + 1]! < -0.99) front.push(t);

const round = (v: number) => Math.round(v * 1e6) / 1e6;
const annotations: Annotation[] = [
  {
    id: 'a1',
    order: 0,
    kind: 'point',
    title: 'Top face',
    body: 'The top of the cube, 60 mm above the mat.',
    anchor: { position: [0, 0, 0.06], normal: [0, 0, 1] },
  },
  {
    id: 'a2',
    order: 1,
    kind: 'region',
    title: 'Front face',
    body: 'The face that points at the visitor (FRONT on the mat).',
    link: 'https://example.com',
    anchor: { position: [0, -0.03, 0.03], normal: [0, -1, 0] },
    triangles: front,
  },
];

const now = '2026-09-24T00:00:00.000Z';
const project: Project = {
  id,
  ownerId: '00000000-0000-0000-0000-000000000000',
  title,
  description: 'A 60 mm cube resting as printed. Generated by scripts/make-mock-project.ts.',
  status: 'published',
  createdAt: now,
  updatedAt: now,
  geometryVersion: 1,
  model: {
    glbPath: 'fixtures/mock-cube.glb',
    triangleCount: prepared.triangleCount,
    boundsMm: { size: prepared.boundsMm.size.map(round) as Vec3 },
    sourceScale: loaded.sourceScale,
  },
  objectToMat: prepared.objectToMat.map(round),
  calibration: { dxMm: 0, dyMm: 0, dzMm: 0, yawDeg: 0 },
  mat: { ...mat.meta, svgPath: 'fixtures/mock-cube-mat.svg' },
  annotations,
};

writeFileSync(join(pub, 'mock-cube.glb'), prepared.glb);
writeFileSync(join(pub, 'mock-cube-mat.svg'), mat.svg);
writeFileSync(join(pub, 'mock-cube-mat.pdf'), mat.pdf);
writeFileSync(
  join(root, 'tests/fixtures/project.mock.json'),
  JSON.stringify(project, null, 2) + '\n',
);
console.log(
  `mock project: ${prepared.triangleCount} tris, front region ${front.length} tris, ${mat.meta.tags.length} tags`,
);
